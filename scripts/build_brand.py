"""Build a font-independent SVG wordmark from the canonical vector mark.

Requires fonttools; uses the Windows Malgun Gothic Bold font for outlines.
Raster exports are generated by scripts/export-brand.mjs in ego-browser.
"""
from pathlib import Path
from fontTools.ttLib import TTFont
from fontTools.pens.svgPathPen import SVGPathPen

root = Path(__file__).resolve().parents[1]
brand = root / 'assets' / 'brand'
font = TTFont('C:/Windows/Fonts/malgunbd.ttf')
glyphs = font.getGlyphSet()
cmap = font.getBestCmap()
units = font['head'].unitsPerEm
scale = 44 / units
x = 0
paths = []
for char in '놀토의':
    name = cmap[ord(char)]
    pen = SVGPathPen(glyphs)
    glyphs[name].draw(pen)
    paths.append(f'<path transform="translate({x} 0)" d="{pen.getCommands()}"/>')
    x += glyphs[name].width
mark = (brand / 'knoltalk-mark.svg').read_text(encoding='utf-8')
art = mark[mark.index('  <rect'):mark.rindex('</svg>')]
svg = f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 254 100" fill="none" role="img" aria-labelledby="title">
<title id="title">놀토의 로고</title>
{art}
<g transform="translate(112 65) scale({scale} {-scale})" fill="#182632">{''.join(paths)}</g>
</svg>
'''
(brand / 'knoltalk-logo.svg').write_text(svg, encoding='utf-8')
print('Built knoltalk-logo.svg (outlined text)')
